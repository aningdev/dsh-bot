// Bundle only public client entrypoints. The installed official dsh owns the Host.
for (const name of ['sdk', 'presets']) {
  const result = await Bun.build({ entrypoints: [`apps/client/frontend/infrastructure/dsh/${name}.ts`], target: 'node', format: 'esm', outdir: 'apps/client/frontend/infrastructure/dsh' })
  if (!result.success) throw new AggregateError(result.logs, `Cannot build ${name}`)
}

// Legacy compatibility assets have one source, shared with the existing management scripts.
const { release } = await Bun.file('scripts/backend/pinned-version.json').json()
if (typeof release !== 'string' || !release.trim()) throw new Error('Missing pinned runtime version')
const launchScript = await Bun.file('scripts/backend/launch.sh').text()
await Bun.write('apps/client/frontend/infrastructure/host/legacy/assets.ts', `// Generated by scripts/prepare-client.ts; do not edit.\nexport const expectedVersion = ${JSON.stringify(release.trim())}\nexport const launchScript = ${JSON.stringify(launchScript)}\n`)
